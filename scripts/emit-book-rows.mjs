#!/usr/bin/env node
/**
 * Emits the SQL that publishes the Christian Books shelf into Supabase.
 *
 *   node scripts/emit-book-rows.mjs --seller <auth-user-uuid>
 *
 * Same contract as scripts/emit-library-rows.mjs: the output is reviewable SQL
 * generated from library/books.generated.json, so a row can never describe a
 * file that is not in public/library/books/. Run `npm run books:check` first.
 *
 * Rows are keyed by original_storage_path = 'christian-books/<slug>.pdf', which
 * is the same key the app uses to match a row back to its catalogue entry.
 * Everything is free: price 0, is_free true, no DRM, status active.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = path.join(ROOT, 'library', 'books.generated.json')

const args = process.argv.slice(2)
const help = args.includes('--help')
const sellerIndex = args.indexOf('--seller')
const sellerId = sellerIndex >= 0 ? args[sellerIndex + 1] : null

if (help || !sellerId) {
    console.log(`
Usage: node scripts/emit-book-rows.mjs --seller <auth-user-uuid>

  --seller   public.users.uid of the official ZikShare account that owns the rows

Pipe to a file and run it with the service role key, or paste it into the
Supabase SQL editor. The service role key must never reach the browser.
`)
    process.exit(help ? 0 : 1)
}

if (!/^[0-9a-f-]{36}$/i.test(sellerId)) {
    console.error('[book-rows] FAILED: --seller must be a uuid from public.users.uid')
    process.exit(1)
}

const raw = JSON.parse(fs.readFileSync(CATALOG, 'utf8'))
const books = raw.books
if (!Array.isArray(books) || books.length === 0) {
    console.error('[book-rows] FAILED: catalogue has no books. Run "npm run books:import".')
    process.exit(1)
}

const columns =
    '(seller_id, title, description, price, currency, category, subcategory, course_code, level, faculty, department, domain, original_storage_path, page_count, file_size_bytes, status, drm_enabled, is_free)'
const fields = '(slug text, t text, s text, st text, lv text, fa text, dp text, dn text, pc int, bs bigint)'
const conflict = `on conflict (seller_id, original_storage_path) where original_storage_path is not null do update set
    title = excluded.title,
    description = excluded.description,
    price = 0,
    category = excluded.category,
    subcategory = excluded.subcategory,
    level = excluded.level,
    faculty = excluded.faculty,
    department = excluded.department,
    domain = excluded.domain,
    page_count = excluded.page_count,
    file_size_bytes = excluded.file_size_bytes,
    status = 'active',
    drm_enabled = false,
    is_free = true,
    updated_at = now();`

const rows = books.map((b) => ({
    slug: b.slug,
    t: b.title,
    s: b.subtitle,
    st: 'textbooks',
    lv: 'All levels',
    fa: 'Christian Literature',
    dp: b.author,
    dn: 'Christian Books',
    pc: b.page_count,
    bs: b.file_size_bytes,
}))

console.log('-- Generated by scripts/emit-book-rows.mjs. Do not edit by hand.')
console.log(`-- ${rows.length} free Christian Books, seller ${sellerId}.`)
console.log('-- Every row is free: price 0, is_free true, no DRM, status active.')
console.log('-- Category "Academic & Study Materials" is the marketplace bucket that')
console.log('-- already carries PDFs; the domain column keeps them on their own shelf.\n')

const json = JSON.stringify(rows).replace(/\$/g, '\\u0024')
console.log(`insert into public.digital_products ${columns}`)
console.log(`select '${sellerId}'::uuid, j.t, j.s, 0, 'NGN', 'Academic & Study Materials', j.st, null, j.lv, j.fa, j.dp, j.dn,`)
console.log(`       'christian-books/' || j.slug || '.pdf', j.pc, j.bs, 'active', false, true`)
console.log(`from jsonb_to_recordset($json$${json}$json$::jsonb) as j${fields}`)
console.log(conflict)
