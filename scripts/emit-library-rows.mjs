#!/usr/bin/env node
/**
 * Emits the SQL that publishes the authored library catalog into Supabase.
 *
 * Use this when the machine running the seed cannot reach Supabase over HTTPS
 * (locked-down sandboxes, CI with no egress, or a DBA who prefers reviewable
 * SQL). It reads `library/catalog.generated.json`, so it can never drift from
 * the PDFs: run `npm run library:build` first and every row here matches a real
 * file.
 *
 *   node scripts/emit-library-rows.mjs --seller <auth-user-uuid>
 *   node scripts/emit-library-rows.mjs --seller <uuid> --chunk 20 > rows.sql
 *
 * Guarantees baked into the output:
 *   * price = 0, is_free = true, drm_enabled = false  (the library is free)
 *   * status = 'active'
 *   * one row per pack via the (seller_id, original_storage_path) unique index
 *
 * The `description` column receives the authored subtitle, which is short and
 * exact. The app renders the full authored description from the catalog, so a
 * row can never invent copy the catalog does not contain.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = path.join(ROOT, 'library', 'catalog.generated.json')

const args = process.argv.slice(2)
const help = args.includes('--help')
const sellerIndex = args.indexOf('--seller')
const chunkIndex = args.indexOf('--chunk')
const sellerId = sellerIndex >= 0 ? args[sellerIndex + 1] : null
const chunkSize = chunkIndex >= 0 ? Number(args[chunkIndex + 1]) : 40

if (help || !sellerId) {
    console.log(`
Usage: node scripts/emit-library-rows.mjs --seller <auth-user-uuid> [--chunk 40]

  --seller   public.users.uid of the official ZikShare account that owns the rows
  --chunk    rows per INSERT statement (default 40)

Pipe to a file and run it with the service role key, or paste it into the
Supabase SQL editor. The service role key must never reach the browser.
`)
    process.exit(help ? 0 : 1)
}

if (!/^[0-9a-f-]{36}$/i.test(sellerId)) {
    console.error('[rows] FAILED: --seller must be a uuid from public.users.uid')
    process.exit(1)
}
if (!Number.isInteger(chunkSize) || chunkSize < 1 || chunkSize > 80) {
    console.error('[rows] FAILED: --chunk must be an integer between 1 and 80')
    process.exit(1)
}

const raw = JSON.parse(fs.readFileSync(CATALOG, 'utf8'))
const packs = Array.isArray(raw) ? raw : raw.packs
if (!Array.isArray(packs) || packs.length === 0) {
    console.error('[rows] FAILED: catalog has no packs. Run "npm run library:build".')
    process.exit(1)
}

const columns = '(seller_id, title, description, price, currency, category, subcategory, course_code, level, faculty, department, domain, original_storage_path, preview_path, page_count, file_size_bytes, status, drm_enabled, is_free)'
const fields = '(slug text, t text, s text, st text, cc text, lv text, fa text, dp text, dn text, pc int, bs bigint)'
const conflict = `on conflict (seller_id, original_storage_path) where original_storage_path is not null do update set
    title = excluded.title,
    description = excluded.description,
    price = 0,
    category = excluded.category,
    subcategory = excluded.subcategory,
    course_code = excluded.course_code,
    level = excluded.level,
    faculty = excluded.faculty,
    department = excluded.department,
    domain = excluded.domain,
    preview_path = excluded.preview_path,
    page_count = excluded.page_count,
    file_size_bytes = excluded.file_size_bytes,
    status = 'active',
    drm_enabled = false,
    is_free = true,
    updated_at = now();`

console.log('-- Generated by scripts/emit-library-rows.mjs. Do not edit by hand.')
console.log(`-- ${packs.length} free library packs, seller ${sellerId}.`)
console.log('-- Every row is free: price 0, is_free true, no DRM, status active.\n')

for (let i = 0; i < packs.length; i += chunkSize) {
    const chunk = packs.slice(i, i + chunkSize).map((p) => ({
        slug: p.slug,
        t: p.title,
        s: p.subtitle,
        st: p.subcategory,
        cc: p.code || null,
        lv: p.level,
        fa: p.faculty,
        dp: p.department,
        dn: p.domain,
        pc: p.page_count,
        bs: p.file_size_bytes,
    }))

    const json = JSON.stringify(chunk).replace(/\$/g, '\\u0024')

    console.log(`insert into public.digital_products ${columns}`)
    console.log(`select '${sellerId}'::uuid, j.t, j.s, 0, 'NGN', 'Academic & Study Materials', j.st, j.cc, j.lv, j.fa, j.dp, j.dn,`)
    console.log(`       'official-library/' || j.slug || '.pdf', '/library/previews/' || j.slug || '.pdf',`)
    console.log(`       j.pc, j.bs, 'active', false, true`)
    console.log(`from jsonb_to_recordset($json$${json}$json$::jsonb) as j${fields}`)
    console.log(conflict)
    console.log('')
}
